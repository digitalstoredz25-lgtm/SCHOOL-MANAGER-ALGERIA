// School Manager — service worker
// Caches only the static app shell (HTML/manifest/icons) so the app can
// launch offline. It deliberately does NOT cache calls to your Supabase
// Edge Function or the QR code images — those must always be live.

const CACHE_NAME = 'school-manager-shell-v1';
const SHELL_FILES = [
  './index.html',
  './manifest.json',
  './icons/icon-192.png',
  './icons/icon-512.png',
];

self.addEventListener('install', (event) => {
  event.waitUntil(
    caches.open(CACHE_NAME).then((cache) => cache.addAll(SHELL_FILES))
  );
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) =>
      Promise.all(keys.filter((k) => k !== CACHE_NAME).map((k) => caches.delete(k)))
    )
  );
  self.clients.claim();
});

self.addEventListener('fetch', (event) => {
  const url = new URL(event.request.url);
  const isShellRequest = event.request.mode === 'navigate' || SHELL_FILES.some((f) => url.pathname.endsWith(f.replace('./', '')));

  if (!isShellRequest) return; // let the network handle API calls, photos, QR codes as normal

  event.respondWith(
    caches.match(event.request).then((cached) => {
      const network = fetch(event.request)
        .then((response) => {
          caches.open(CACHE_NAME).then((cache) => cache.put(event.request, response.clone()));
          return response;
        })
        .catch(() => cached);
      return cached || network;
    })
  );
});
